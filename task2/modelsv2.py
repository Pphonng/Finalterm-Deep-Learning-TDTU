#Theo dõi điểm cảm xúc theo thời gian, phát hiện xu hướng cải thiện / suy giảm, tính streak tích cực
class MoodTracker:
    """
    Theo dõi lịch sử cảm xúc, tính toán:
    - Mood score timeline (dựa trên EMOTION_SCORE)
    - Rolling average (cửa sổ N bước)
    - Positive streak (số lần liên tiếp cảm xúc tích cực)
    - Trend detection (đang cải thiện / ổn định / suy giảm)
    """

    TREND_WINDOW = 5          
    ROLLING_WINDOW = 3        

    def __init__(self):
        self.memory: list[dict] = []  # {"time": datetime, "emotion": str, "score": int, "text": str}


    def log(self, emotion: str, text: str = ""):
        score = EMOTION_SCORE.get(emotion, 0)
        self.memory.append({
            "time":    datetime.now(),
            "emotion": emotion,
            "score":   score,
            "text":    text,
        })

    def scores(self) -> list[int]:
        return [e["score"] for e in self.memory]

    def rolling_avg(self, window: int | None = None) -> list[float]:
        w = window or self.ROLLING_WINDOW
        s = self.scores()
        return [round(sum(s[max(0, i-w+1):i+1]) / min(i+1, w), 2) for i in range(len(s))]


    def current_trend(self) -> str:
        """'improving' | 'stable' | 'declining'"""
        s = self.scores()
        if len(s) < 2:
            return "stable"
        window = s[-self.TREND_WINDOW:]
        slope = (window[-1] - window[0]) / max(len(window) - 1, 1)
        if slope > 0.3:  return "improving "
        if slope < -0.3: return "declining"
        return "stable "

    def positive_streak(self) -> int:
        streak = 0
        for entry in reversed(self.memory):
            if entry["score"] > 0:
                streak += 1
            else:
                break
        return streak

    def best_emotion(self) -> str | None:
        if not self.memory:
            return None
        return max(self.memory, key=lambda e: e["score"])["emotion"]

    def worst_emotion(self) -> str | None:
        if not self.memory:
            return None
        return min(self.memory, key=lambda e: e["score"])["emotion"]


    def summary_stats(self) -> dict:
        s = self.scores()
        if not s:
            return {}
        return {
            "total_logs":      len(s),
            "avg_score":       round(sum(s) / len(s), 2),
            "best_emotion":    self.best_emotion(),
            "worst_emotion":   self.worst_emotion(),
            "trend":           self.current_trend(),
            "positive_streak": self.positive_streak(),
            "positive_pct":    round(100 * sum(1 for x in s if x > 0) / len(s), 1),
            "negative_pct":    round(100 * sum(1 for x in s if x < 0) / len(s), 1),
        }

