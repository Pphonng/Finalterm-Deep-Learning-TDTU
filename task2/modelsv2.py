class WeeklySummary:
    """
    Sinh báo cáo cảm xúc theo tuần từ MoodTracker.
    - Bar chart: tần suất từng cảm xúc
    - Pie chart: phân bố Positive / Neutral / Negative
    - Bảng thống kê văn bản (Markdown-friendly)
    """

    def __init__(self, mood_tracker: MoodTracker):
        self.tracker = mood_tracker

    def _filter_week(self, week_offset: int = 0) -> list[dict]:
        """week_offset=0 → tuần hiện tại, -1 → tuần trước."""
        today = datetime.now().date()
        start = today - timedelta(days=today.weekday()) + timedelta(weeks=week_offset)
        end   = start + timedelta(days=6)
        return [
            e for e in self.tracker.memory
            if start <= e["time"].date() <= end
        ]

    def text_report(self, week_offset: int = 0) -> str:
        entries = self._filter_week(week_offset)
        if not entries:
            return "Không có dữ liệu cho tuần này."

        counts = Counter(e["emotion"] for e in entries)
        scores = [e["score"] for e in entries]
        pos = sum(1 for s in scores if s > 0)
        neu = sum(1 for s in scores if s == 0)
        neg = sum(1 for s in scores if s < 0)
        avg = round(sum(scores) / len(scores), 2)

        today = datetime.now().date()
        start = today - timedelta(days=today.weekday()) + timedelta(weeks=week_offset)
        end   = start + timedelta(days=6)

        lines = [
            f"## Weekly Emotional Summary ({start} → {end})",
            f"",
            f"| Metric | Value |",
            f"|--------|-------|",
            f"| Tổng lần log | {len(entries)} |",
            f"| Điểm TB | {avg} |",
            f"| Tích cực | {pos} ({round(100*pos/len(entries))}%) |",
            f"| Trung tính | {neu} ({round(100*neu/len(entries))}%) |",
            f"| Tiêu cực | {neg} ({round(100*neg/len(entries))}%) |",
            f"| Cảm xúc phổ biến nhất | {counts.most_common(1)[0][0]} ({counts.most_common(1)[0][1]} lần) |",
            f"",
            f"### Cảm xúc trong tuần",
        ]
        for emo, cnt in counts.most_common(5):
            bar = "█" * cnt
            lines.append(f"- **{emo}**: {bar} {cnt}")

        return "\n".join(lines)

class Retriever:
    def __init__(self):
        self.vectorizer = TfidfVectorizer(
            ngram_range=(1, 2),
            max_features=50_000,
            sublinear_tf=True,
        )
        self.matrix = None
        self.docs: list[str] = []

    def ingest(self, texts: list[str]):
        self.docs   = texts
        self.matrix = self.vectorizer.fit_transform(texts)
        print(f"Ingested {len(texts)} docs, vocab={len(self.vectorizer.vocabulary_)}")

    def search(self, query: str, k: int = 5) -> list[str]:
        if not query.strip() or self.matrix is None:
            return []
        q_vec = self.vectorizer.transform([query])
        scores = cosine_similarity(q_vec, self.matrix)[0]
        top_k  = scores.argsort()[::-1][:k]
        return [self.docs[i] for i in top_k if scores[i] > 0]

    def save(self, path: str):
        os.makedirs(path, exist_ok=True)
        with open(f"{path}/retriever.pkl", "wb") as f:
            pickle.dump({"vectorizer": self.vectorizer,
                         "matrix": self.matrix,
                         "docs": self.docs}, f)

    @classmethod
    def load(cls, path: str) -> "Retriever":
        with open(f"{path}/retriever.pkl", "rb") as f:
            d = pickle.load(f)
        r = cls()
        r.vectorizer = d["vectorizer"]
        r.matrix     = d["matrix"]
        r.docs       = d["docs"]
        print(f"Loaded retriever: {len(r.docs)} docs")
        return r

