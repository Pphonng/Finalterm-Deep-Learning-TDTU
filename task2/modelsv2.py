def build_label_maps(split):

    emotions = sorted(set(split["emotion"]))

    emotion2id = {e: i for i, e in enumerate(emotions)}
    id2emotion = {i: e for e, i in emotion2id.items()}

    behaviors = sorted(set(split["behavior"]))

    behavior2id = {b: i for i, b in enumerate(behaviors)}
    id2behavior = {i: b for b, i in behavior2id.items()}

    return (
        emotion2id,
        id2emotion,
        behavior2id,
        id2behavior,
        len(emotion2id),
        len(behavior2id),
    )

class EmotionDataset(Dataset):

    def __init__(
        self,
        hf_split,
        tokenizer,
        emotion2id,
        behavior2id,
        max_len=256
    ):
        self.data = hf_split
        self.tokenizer = tokenizer
        self.emotion2id = emotion2id
        self.behavior2id = behavior2id
        self.max_len = max_len

    def __len__(self):
        return len(self.data)

    def build_text(self, row):

        situation = row["situation"]
        history = row["chat_history"]

        if isinstance(history, list):
            history = " ".join(history)

        return f"Situation: {situation}\nDialogue: {history}"

    def __getitem__(self, idx):
        row = self.data[idx]
        text = self.build_text(row)
        enc = self.tokenizer(
            text,
            truncation=True,
            padding="max_length",
            max_length=self.max_len,
            return_tensors="pt"
        )

        return {
            "input_ids": enc["input_ids"].squeeze(0),
            "attention_mask": enc["attention_mask"].squeeze(0),

            "emotion": torch.tensor(
                self.emotion2id[row["emotion"]],
                dtype=torch.long
            ),

            "behavior": torch.tensor(
                self.behavior2id[row["behavior"]],
                dtype=torch.long
            ),
        }

class EmotionModel(nn.Module):

    def __init__(self, n_emo, n_behavior=None, base_model=EMO_MODEL_NAME):

        super().__init__()

        self.encoder = AutoModel.from_pretrained(base_model)
        h = self.encoder.config.hidden_size

        self.emotion_head = self._head(h, n_emo)

        self.behavior_head = (
            self._head(h, n_behavior)
            if n_behavior is not None else None
        )

    @staticmethod
    def _head(hidden, n_out):
        return nn.Sequential(
            nn.Linear(hidden, 256),
            nn.GELU(),
            nn.Dropout(0.1),
            nn.Linear(256, n_out),
        )

    def forward(self, input_ids, attention_mask):

        out = self.encoder(
            input_ids=input_ids,
            attention_mask=attention_mask
        )

        cls = out.last_hidden_state[:, 0]

        logits = {
            "emotion": self.emotion_head(cls)
        }

        if self.behavior_head is not None:
            logits["behavior"] = self.behavior_head(cls)

        return logits
    @torch.no_grad()
    def predict(self, text: str, tokenizer, id2emotion, id2behavior=None) -> dict:
        self.eval()
        
        device = next(self.parameters()).device 

        batch = tokenizer(
            text, truncation=True, padding=True,
            max_length=128, return_tensors="pt",
        )

        # toàn bộ batch lên cùng device với model
        batch = {k: v.to(device) for k, v in batch.items()}
        logits = self(batch["input_ids"], batch["attention_mask"])
        
        emotion_id = logits["emotion"].argmax(-1).item()
        result = {"emotion": id2emotion[emotion_id]} 
        
        if "behavior" in logits and id2behavior:
            behavior_id = logits["behavior"].argmax(-1).item()
            result["behavior"] = id2behavior[behavior_id]
            
        return result
    



